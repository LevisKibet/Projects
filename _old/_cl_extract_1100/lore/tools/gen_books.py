"""The lore books, from tools/lore_books.md:
  src/main/java/.../LoreBooks.java          the books as written-book stacks (lecterns, item frames, other mods' chests)
  data/ancientpeaks_lore/loot_tables/books/  one table per group (chests in our buildings roll these)

    python3 tools/gen_books.py
"""
import re, json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
md = (ROOT / "tools/lore_books.md").read_text()

AUTHORS = {1: "Maeve", 2: "Maeve", 3: "A refugee", 4: "A woodcutter", 5: "The village baker", 6: "A child", 7: "The Community Book",
           8: "The blacksmith", 9: "A weaver", 10: "A guard", 11: "The watchman", 12: "Captain Andrew", 13: "Guard Post 4",
           14: "The captain", 15: "The night watch", 16: "Brother Bran", 17: "A monk", 18: "A monk", 19: "Unknown hand",
           20: "A monk", 21: "Brother Thomas", 22: "The sanctuary", 23: "The dockmaster", 24: "Unknown hand", 25: "A fisherman",
           26: "The warband chief", 27: "Unknown hand", 28: "Merlin",
           29: "Arthur", 30: "Arthur", 31: "Sergeant Pell"}
GROUP = {**{i: "village" for i in range(1, 10)}, **{i: "guard" for i in range(10, 16)}, **{i: "chapel" for i in range(16, 23)},
         **{i: "harbour" for i in range(23, 26)}, 26: "raider", 27: "raider", 28: "merlin",
         29: "court", 30: "court", 31: "guard"}
# the supply carts the raiders robbed: the books about the carts, the roads and the raiders
CART = [5, 10, 14, 18, 26, 27, 12]

def clean(t):
    t = re.sub(r"\*([^*]+)\*", r"\1", t)          # italics
    t = t.replace("--", ",").replace("—", ",").strip()
    return t

books = []
for m in re.finditer(r"### Book (\d+): \*(.+?)\*\n(.*?)(?=\n### Book |\n## |\Z)", md, re.S):
    n, title, body = int(m.group(1)), m.group(2).strip(), m.group(3)
    pages = []
    for pm in re.finditer(r"\*\*Page \d+\*\*\n\n(.*?)(?=\n\*\*Page |\n---|\Z)", body, re.S):
        lines = [l[1:].strip() if l.startswith(">") else l.strip() for l in pm.group(1).strip().splitlines()]
        text = "\n".join(clean(l.rstrip("\\ ").rstrip()) for l in lines if l.strip() != "")
        text = re.sub(r"(?m)^- ", "• ", text)                              # list items only
        text = text.replace(" - ", ", ")                                    # no dashes in the prose
        pages.append(text)
    # a written book page shows about 240 characters: split longer pages at a sentence
    out = []
    for p in pages:
        while len(p) > 250:
            cut = max(p.rfind(". ", 0, 245), p.rfind("\n", 0, 245))
            if cut < 80: cut = p.rfind(" ", 0, 245)
            out.append(p[:cut + 1].strip()); p = p[cut + 1:].strip()
        out.append(p)
    t = title if len(title) <= 32 else title.split(":")[-1].strip()[:32]
    books.append({"n": n, "title": t, "author": AUTHORS[n], "pages": out, "group": GROUP[n]})
assert len(books) == 31, len(books)

# ---- Java
def js(s): return json.dumps(s)
rows = []
for b in books:
    pages = ", ".join(js(p) for p in b["pages"])
    rows.append(f'        new Book({b["n"]}, {js(b["title"])}, {js(b["author"])}, "{b["group"]}", new String[]{{{pages}}}),')
java = f'''package com.ronald.ancientpeaks_lore;

import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.StringTag;
import net.minecraft.network.chat.Component;
import net.minecraft.util.RandomSource;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;

import java.util.Arrays;
import java.util.List;

/**
 * The lore books found about Logres (generated by tools/gen_books.py from tools/lore_books.md - edit the markdown,
 * not this file). Groups: village, guard, chapel, harbour, raider, merlin (his journal, only in his cabin); "cart" is the books found by the raided carts.
 */
public final class LoreBooks {{
    private LoreBooks() {{}}
    public record Book(int n, String title, String author, String group, String[] pages) {{}}

    public static final List<Book> ALL = List.of(
{chr(10).join(rows)[:-1]}
    );
    static final int[] CART = {{{", ".join(str(c) for c in CART)}}};

    public static Book byNumber(int n) {{ return ALL.get(n - 1); }}

    /** A random book of a group ("all" for any, "cart" for the raided carts). */
    public static Book random(RandomSource r, String group) {{
        if (group.equals("cart")) return byNumber(CART[r.nextInt(CART.length)]);
        // Merlin's own journal is only ever found in his cabin (group "merlin"), never among the rest
        List<Book> pool = group.equals("all") ? ALL.stream().filter(b -> !b.group().equals("merlin")).toList()
                : ALL.stream().filter(b -> b.group().equals(group)).toList();
        if (pool.isEmpty()) pool = ALL;
        return pool.get(r.nextInt(pool.size()));
    }}

    public static CompoundTag tag(Book b) {{
        CompoundTag t = new CompoundTag();
        t.putString("title", b.title());
        t.putString("author", b.author());
        t.putByte("resolved", (byte) 1);
        t.putInt("generation", 3);                                 // "tattered"
        t.putInt("LoreId", b.n());                                 // the compendium knows it by this
        ListTag pages = new ListTag();
        for (String p : b.pages()) pages.add(StringTag.valueOf(Component.Serializer.toJson(Component.literal(p))));
        t.put("pages", pages);
        return t;
    }}

    public static ItemStack stack(Book b) {{
        ItemStack s = new ItemStack(Items.WRITTEN_BOOK);
        s.setTag(tag(b));
        return s;
    }}
}}
'''
(ROOT / "src/main/java/com/ronald/ancientpeaks_lore/LoreBooks.java").write_text(java)

# ---- loot tables
def snbt_str(s): return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
def entry(b, w=1):
    pages = ",".join(snbt_str(json.dumps({"text": p})) for p in b["pages"])
    tag = "{title:%s,author:%s,resolved:1b,generation:3,LoreId:%d,pages:[%s]}" % (snbt_str(b["title"]), snbt_str(b["author"]), b["n"], pages)
    return {"type": "minecraft:item", "name": "minecraft:written_book", "weight": w, "functions": [{"function": "minecraft:set_nbt", "tag": tag}]}
out = ROOT / "src/main/resources/data/ancientpeaks_lore/loot_tables/books"
out.mkdir(parents=True, exist_ok=True)
groups = {g: [b for b in books if b["group"] == g] for g in ("village", "guard", "chapel", "harbour", "raider", "merlin", "court")}
groups["all"] = [b for b in books if b["group"] != "merlin"]
groups["cart"] = [b for b in books if b["n"] in CART]
for g, bs in groups.items():
    (out / f"{g}.json").write_text(json.dumps({"type": "minecraft:chest", "pools": [{"rolls": 1, "entries": [entry(b) for b in bs]}]}, indent=1))
print(len(books), "books;", {g: len(v) for g, v in groups.items()}, "max pages", max(len(b["pages"]) for b in books))
